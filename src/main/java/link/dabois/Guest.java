package link.dabois;

import java.io.*;
import java.net.*;
import java.nio.file.*;
import java.security.MessageDigest;
import java.security.cert.*;
import java.util.Properties;
import java.util.concurrent.Semaphore;
import javax.net.ssl.*;

final class Guest {
    record Invite(String host, int port, String name, String fingerprint, int voicePort,
                  EmbeddedZeroTier.Settings overlay) {
        Invite(String host, int port, String name, String fingerprint, int voicePort) {
            this(host, port, name, fingerprint, voicePort, null);
        }

        Invite(String host, int port, String name, String fingerprint) {
            this(host, port, name, fingerprint, 0);
        }

        static Invite packaged() throws IOException {
            try (InputStream in = Guest.class.getResourceAsStream("/" + HostSetup.INVITE)) {
                if (in == null) {
                    throw new IOException("Use the friends JAR generated by your server host.");
                }
                Properties invite = new Properties();
                invite.load(in);
                int voice = invite.containsKey("voicePort") ? HostSetup.port(invite.getProperty("voicePort")) : 0;
                return new Invite(invite.getProperty("host"), HostSetup.port(invite.getProperty("port")),
                        invite.getProperty("name"), invite.getProperty("fingerprint"), voice,
                        EmbeddedZeroTier.Settings.read(invite));
            }
        }
    }

    private record Session(ServerSocket listener, VoiceTunnel.Local voice) {
        String address() {
            return "127.0.0.1:" + listener.getLocalPort();
        }

        void close() {
            Link.close(listener);
            if (voice != null) {
                voice.close();
            }
        }
    }

    private static Session session;

    static synchronized String resume(Invite invite, Path file) throws IOException {
        if (session != null) {
            return session.address();
        }
        if (Files.notExists(file)) {
            return null;
        }
        Properties paired = Link.read(file);
        String token = paired.getProperty("token");
        if (token == null || !token.matches("[a-f0-9]{64}")) {
            throw new IOException("Saved pairing is invalid. Pair with a new code.");
        }
        int port = HostSetup.port(paired.getProperty("port"));
        session = start(invite, token, port);
        return session.address();
    }

    static void request(Invite invite, String name, String code, String token) throws IOException {
        try (Socket socket = tls(invite)) {
            DataOutputStream out = new DataOutputStream(socket.getOutputStream());
            out.writeInt(Link.MAGIC);
            out.writeByte(Link.PAIR);
            out.writeUTF(name);
            out.writeUTF(code);
            out.writeUTF(token);
            DataInputStream in = new DataInputStream(socket.getInputStream());
            if (!in.readBoolean()) {
                throw new IOException(in.readUTF());
            }
        }
    }

    static synchronized String remember(Invite invite, Path file, String token) throws IOException {
        int port = session == null ? 0 : session.listener.getLocalPort();
        if (session != null) {
            session.close();
            session = null;
        }
        Session next = start(invite, token, port);
        Properties paired = new Properties();
        paired.setProperty("token", token);
        paired.setProperty("port", Integer.toString(next.listener.getLocalPort()));
        try {
            Link.save(file, paired);
        } catch (IOException e) {
            next.close();
            throw e;
        }
        session = next;
        return next.address();
    }

    private static Session start(Invite invite, String token, int port) throws IOException {
        ServerSocket listener = new ServerSocket();
        try {
            listener.setReuseAddress(true);
            listener.bind(new InetSocketAddress("127.0.0.1", port));
        } catch (IOException e) {
            listener.close();
            throw e;
        }
        Semaphore capacity = new Semaphore(8);
        Thread.startVirtualThread(() -> {
            while (!listener.isClosed()) {
                try {
                    Socket local = listener.accept();
                    if (capacity.tryAcquire()) {
                        Thread.startVirtualThread(() -> {
                            try (local; Socket remote = tls(invite)) {
                                local.setTcpNoDelay(true);
                                DataOutputStream out = new DataOutputStream(remote.getOutputStream());
                                out.writeInt(Link.MAGIC);
                                out.writeByte(Link.PLAY);
                                out.writeUTF(token);
                                if (new DataInputStream(remote.getInputStream()).readBoolean()) {
                                    Link.bridge(local, remote);
                                }
                            } catch (IOException ignored) {
                                // Minecraft reports a failed connection in its normal UI.
                            } finally {
                                capacity.release();
                            }
                        });
                    } else {
                        local.close();
                    }
                } catch (IOException e) {
                    Link.close(listener);
                }
            }
        });
        VoiceTunnel.Local voice = null;
        if (invite.voicePort > 0) {
            try {
                voice = new VoiceTunnel.Local(invite, token);
            } catch (IOException e) {
                System.err.println("DABOIS Link could not open the local voice port: " + e.getMessage());
            }
        }
        return new Session(listener, voice);
    }

    static SSLSocket tls(Invite invite) throws IOException {
        X509TrustManager trust = new X509TrustManager() {
            @Override
            public void checkServerTrusted(X509Certificate[] chain, String authType) throws CertificateException {
                if (chain == null || chain.length == 0 || !MessageDigest.isEqual(
                        Link.digest(chain[0].getEncoded()), Link.HEX.parseHex(invite.fingerprint))) {
                    throw new CertificateException("The server certificate does not match this invite.");
                }
                chain[0].checkValidity();
            }

            @Override
            public void checkClientTrusted(X509Certificate[] chain, String authType) throws CertificateException {
                throw new CertificateException("Client certificates are unsupported.");
            }

            @Override
            public X509Certificate[] getAcceptedIssuers() {
                return new X509Certificate[0];
            }
        };
        Socket overlay = EmbeddedZeroTier.connect(invite.overlay);
        Socket tcp = overlay != null ? overlay : Link.connect(invite.host, invite.port);
        try {
            SSLContext context = SSLContext.getInstance("TLS");
            context.init(null, new TrustManager[]{trust}, null);
            SSLSocket socket = (SSLSocket) context.getSocketFactory().createSocket(
                    tcp, invite.host, invite.port, true);
            socket.setEnabledProtocols(new String[]{"TLSv1.3"});
            socket.startHandshake();
            return socket;
        } catch (Exception e) {
            Link.close(tcp);
            throw new IOException("Could not verify the server connection: " + e.getMessage(), e);
        }
    }
}
